class FakeAI:
    """Scripted stand-in for the model provider. Records every prompt; can time out."""

    configured = True

    def __init__(self, responses: list[Any] | Callable[[str, str], Any] | None = None, raise_exc: Exception | None = None):
        self.responses = responses if responses is not None else []
        self.raise_exc = raise_exc
        self.calls: list[dict[str, Any]] = []

    def generate_json(self, *, tier, system, user, schema, inline=None, temperature=0.2, max_tokens=900,
                      timeout_s=12.0, cache=True):
        self.calls.append({"tier": tier, "system": system, "user": user, "inline": bool(inline), "schema": schema})
        if self.raise_exc:
            raise self.raise_exc
        if callable(self.responses):
            data = self.responses(system, user)
        else:
            if not self.responses:
                from app.ai.gemini import AIUnavailable
                raise AIUnavailable("no_scripted_response")
            data = self.responses.pop(0)
        return {"data": data, "latency_ms": 3, "cached": False, "tokens": {"in": 1, "out": 1}}

    def embed(self, texts, timeout_s=8.0, task_types=None, model=None):
        from app.ai.gemini import AIUnavailable
        raise AIUnavailable("not_configured")


