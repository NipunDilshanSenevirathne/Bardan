"""Release test harness: fixtures, the Appendix D acceptance-case marker and the JSON report shown in the
Trust Centre (finalsystem.md §29, Appendix D).

Tests never call a model provider or the network: the AI key is cleared before the app is imported, and the
few tests that exercise AI paths install a scripted stand-in (``fake_ai``). Expected outcomes were written from
the specification, not generated by the code under test.

Run:  pytest                      (fast feedback)
      pytest --bardan-report      (also writes reports/test_report.json for the Trust Centre)
"""
