class Persona:
    """One signed-in synthetic persona in one sandbox."""

    def __init__(self, client, key: str, sandbox_id: str | None = None, lang: str = "en"):
        body = {"persona": key, **({"sandbox_id": sandbox_id} if sandbox_id else {})}
        r = client.post("/v1/sandbox/session", json=body)
        assert r.status_code == 200, r.text
        j = r.json()
        self.client, self.key, self.lang = client, key, lang
        self.sid, self.token = j["sandbox_id"], j["token"]
        self.actor, self.role = j["persona"]["actor"], j["persona"]["role"]

    @property
    def headers(self) -> dict[str, str]:
        return {"Authorization": f"Bearer {self.token}", "X-Bardan-Lang": self.lang}

    def get(self, path: str, **kw):
        return self.client.get(path, headers={**self.headers, **kw.pop("headers", {})}, **kw)

    def post(self, path: str, body: Any = None, **kw):
        return self.client.post(path, json={} if body is None else body,
                                headers={**self.headers, **kw.pop("headers", {})}, **kw)

    def delete(self, path: str, **kw):
        return self.client.delete(path, headers={**self.headers, **kw.pop("headers", {})}, **kw)


class Site:
    """A fresh judge sandbox; ``site.as_("ravi")`` signs in any persona into the same sandbox."""

    def __init__(self, client):
        self.client = client
        self.sup = Persona(client, "joseph")
        self.sid = self.sup.sid
        self._cache: dict[tuple[str, str], Persona] = {("joseph", "en"): self.sup}

    def as_(self, key: str, lang: str = "en") -> Persona:
        k = (key, lang)
        if k not in self._cache:
            self._cache[k] = Persona(self.client, key, self.sid, lang)
        return self._cache[k]

    @property
    def sb(self):
        from app.core.sandbox import STORE
        sb = STORE.peek(self.sid)
        assert sb is not None
        return sb

    def scene(self, scene_id: str) -> dict[str, Any]:
        r = self.sup.post("/v1/sandbox/scene", {"scene": scene_id})
        assert r.status_code == 200, r.text
        return r.json()


