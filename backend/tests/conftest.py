# --------------------------------------------------------------------------------------------- markers
def pytest_addoption(parser):
    parser.addoption("--bardan-report", action="store_true", default=False,
                     help="write reports/test_report.json (release test report for the Trust Centre)")


def pytest_configure(config):
    config.addinivalue_line("markers", "tcase(*ids): Appendix D acceptance cases covered by this test")


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    ids: list[str] = []
    for m in item.iter_markers("tcase"):
        ids.extend(m.args)
    rep.t_cases = sorted(set(ids))
    fn = getattr(item, "function", None)
    rep.doc = ((fn.__doc__ or "").strip().splitlines() or [""])[0] if fn else ""
    mod = getattr(item, "module", None)
    rep.suite_title = ((mod.__doc__ or "").strip().splitlines() or [""])[0] if mod else ""


def pytest_runtest_logreport(report):
    if report.when == "call" or (report.when == "setup" and report.outcome != "passed"):
        _RESULTS.append({
            "id": report.nodeid, "file": report.nodeid.split("::")[0].split("/")[-1],
            "name": report.nodeid.split("::", 1)[-1], "outcome": report.outcome,
            "t_cases": getattr(report, "t_cases", []), "doc": getattr(report, "doc", ""),
            "suite_title": getattr(report, "suite_title", ""), "duration_s": round(report.duration, 3),
            **({"message": str(report.longrepr)[-600:]} if report.failed else {}),
        })


def pytest_sessionfinish(session, exitstatus):
    if not session.config.getoption("--bardan-report") or not _RESULTS:
        return
    suites: dict[str, dict[str, Any]] = {}
    for r in _RESULTS:
        s = suites.setdefault(r["file"], {"name": r["file"], "title": r["suite_title"], "tests": []})
        keys = ["id", "name", "outcome", "t_cases", "doc", "duration_s"] + (["message"] if "message" in r else [])
        s["tests"].append({k: r[k] for k in keys})
    # Device-side results (TypeScript engine, vitest) are merged when present: same suite, two engines.
    vitest = ROOT.parent / "frontend" / "reports" / "vitest.json"
    if vitest.exists():
        v = json.loads(vitest.read_text(encoding="utf-8"))
        for tr in v.get("testResults", []):
            name = Path(tr["name"]).name
            s = suites.setdefault(name, {"name": name, "title": "Device engine (TypeScript, runs in the browser)",
                                         "tests": []})
            for a in tr.get("assertionResults", []):
                outcome = {"passed": "passed", "failed": "failed"}.get(a["status"], "skipped")
                rec = {"id": f"{name}::{a['title']}", "file": name, "name": a["title"], "outcome": outcome,
                       "t_cases": sorted(set(re.findall(r"\bT\d{2}\b", a["title"]))), "doc": "",
                       "suite_title": s["title"], "duration_s": round((a.get("duration") or 0) / 1000, 3)}
                _RESULTS.append(rec)
                s["tests"].append({k: rec[k] for k in ("id", "name", "outcome", "t_cases", "doc", "duration_s")})
    catalogue = json.loads(CATALOGUE.read_text(encoding="utf-8")) if CATALOGUE.exists() else {"cases": []}
    by_case: dict[str, list[dict[str, Any]]] = {}
    for r in _RESULTS:
        for tc in r["t_cases"]:
            by_case.setdefault(tc, []).append(r)
    cases = []
    for c in catalogue.get("cases", []):
        runs = by_case.get(c["id"], [])
        status = ("failed" if any(x["outcome"] == "failed" for x in runs) else "passed") if runs else \
            ("not_built" if c.get("not_built") else "not_covered")
        cases.append({**c, "status": status, "tests": [x["id"] for x in runs]})
    summary = {"total": len(_RESULTS), "passed": sum(r["outcome"] == "passed" for r in _RESULTS),
               "failed": sum(r["outcome"] == "failed" for r in _RESULTS),
               "skipped": sum(r["outcome"] == "skipped" for r in _RESULTS),
               "duration_s": round(time.time() - _T0, 1)}
    report = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "runner": f"pytest {pytest.__version__} on Python {platform.python_version()}",
        "summary": summary, "suites": sorted(suites.values(), key=lambda s: s["name"]),
        "t_cases_covered": sorted(by_case), "t_cases_total": len(catalogue.get("cases", [])),
        "t_cases_not_covered": [c["id"] for c in cases if c["status"] in ("not_covered", "not_built")],
        "t_cases": cases,
        "note": ("Synthetic data only. Model calls are replaced by scripted stand-ins in tests; live model "
                 "behaviour is measured separately in the evaluation report. The device engine's results come "
                 "from vitest (npm run test:report) when that report exists."),
    }
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=1), encoding="utf-8")


